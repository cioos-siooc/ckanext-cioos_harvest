# Tests
# ---------------------------------------------------------------------------


class TestISO19115_3:
    """Golden-file tests for the full XML → CKAN package dict pipeline.

    Each fixture XML is validated for correct root element, then run through
    the full pipeline and compared against a stored expected JSON.
    """

    @pytest.fixture(autouse=True)
    def setup_harvester(self):
        """Prepare a singleton harvester instance with an empty source config."""
        self.harvester = WAFHarvesterISO19115_3()
        self.harvester.config = {}

    # ------------------------------------------------------------------
    # Structural validation (no CKAN stack required)
    # ------------------------------------------------------------------

    @pytest.mark.parametrize("name", _fixture_names())
    def test_xml_root_element_is_mdb_md_metadata(self, name):
        """Every XML fixture must have ``mdb:MD_Metadata`` as its root element.

        The ISO 19115-3 harvester rejects anything that is not a proper
        ISO 19115-3 document (e.g. ISO 19139 ``gmd:MD_Metadata`` records).
        """
        xml_path = _XML_DIR / f"{name}.xml"
        tree = etree.fromstring(xml_path.read_bytes())
        expected_tag = f"{{{_MDB_NS}}}MD_Metadata"
        assert tree.tag == expected_tag, (
            f"'{name}.xml' has root element <{tree.tag}>, "
            f"expected <{{{{{_MDB_NS}}}}}MD_Metadata>.  "
            "This harvester only accepts ISO 19115-3 documents."
        )

    # ------------------------------------------------------------------
    # Full pipeline golden-file test (requires CKAN stack via app fixture)
    # ------------------------------------------------------------------

    @pytest.mark.parametrize("name", _fixture_names())
    def test_package_dict_matches_expected(self, request, name, app):
        """Parse an XML fixture, build the package dict, compare to expected JSON.

        The ``app`` fixture (provided by pytest-ckan) ensures the full CKAN
        plugin stack — scheming, fluent, composite — is initialised so that
        ``get_package_dict()`` can resolve the dataset schema and language list.

        Missing JSON
        ~~~~~~~~~~~~
        If no JSON file exists for *name*, the current pipeline output (after
        field filtering) is written as the new expected file and the test is
        skipped.  Review then re-run.

        Regenerating
        ~~~~~~~~~~~~
        Pass ``--regenerate-fixtures`` to overwrite all package JSON files.
        """
        xml_path = _XML_DIR / f"{name}.xml"
        json_path = _JSON_DIR / f"{name}.json"

        regenerate = request.config.getoption("--regenerate-fixtures", default=False)

        # --- Step 1: parse XML ---
        xml_bytes = xml_path.read_bytes()
        iso_values = ISODocument(xml_bytes).read_values()
        guid = iso_values.get("guid", "unknown-guid")
        mock_ho = _make_mock_harvest_object(guid)

        # --- Step 2: build package dict ---
        mock_source_pkg = MagicMock()
        mock_source_pkg.owner_org = None

        with (
            patch("ckan.model.Package.get", return_value=mock_source_pkg),
            patch.object(
                self.harvester,
                "_save_object_error",
                side_effect=lambda msg, *a, **kw: log.warning("harvest error: %s", msg),
            ),
        ):
            package_dict = self.harvester.get_package_dict(iso_values, mock_ho)

        result = _filter(_normalise(package_dict))

        # --- Generate golden file if missing or regeneration requested ---
        if not json_path.exists() or regenerate:
            _JSON_DIR.mkdir(parents=True, exist_ok=True)
            json_path.write_text(
                json.dumps(result, indent=2, sort_keys=True, ensure_ascii=False),
                encoding="utf-8",
            )
            action = "Regenerated" if regenerate else "Generated"
            pytest.skip(
                f"{action} expected package JSON for '{name}' → "
                f"tests/fixtures/iso19115_3/01-ckan-package/{name}.json  "
                "Review the file and re-run to validate."
            )

        # --- Compare ---
        expected_raw = json.loads(json_path.read_text(encoding="utf-8"))
        expected = _filter(expected_raw)

        assert result == expected, (
            f"Package dict for '{name}' does not match expected JSON.\n"
            f"  Expected : {json_path}\n"
            f"  To regenerate all fixtures: pytest --regenerate-fixtures"
        )

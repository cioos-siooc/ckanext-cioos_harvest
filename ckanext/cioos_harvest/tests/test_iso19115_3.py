"""Golden-file tests for the full ISO 19115-3 harvester pipeline.

Tests the complete transformation from XML to a CKAN-ready package dict:

    XML
    → ISODocument.read_values()
    → WAFHarvesterISO19115_3.get_package_dict()

Fixture files
-------------
- ``tests/fixtures/iso19115_3/00-xml/<name>.xml``          — input XML
- ``tests/fixtures/iso19115_3/01-ckan-package/<name>.json`` — expected package dict

The expected JSON may be a raw production ``package_show`` API response.
Fields generated by CKAN's database layer or by post-harvest enrichment
services are stripped before comparison using ``_SKIP_FIELDS``.

Workflow
--------
1. Add an ISO 19115-3 XML file to ``00-xml/``.
2. Run ``pytest`` — if no package JSON exists, one is generated from the
   current pipeline output and the test is skipped.
3. Review/edit the generated JSON in ``01-ckan-package/<name>.json``.
4. Re-run — test now asserts pipeline output == stored JSON.

Regenerate all golden files after intentional pipeline changes::

    pytest --regenerate-fixtures
"""

import json
import logging
from pathlib import Path
from unittest.mock import MagicMock, patch

import pytest
from lxml import etree

from ckanext.cioos_harvest.harvesters.waf import WAFHarvesterISO19115_3
from ckanext.cioos_harvest.model.iso19115_3 import ISODocument

log = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------


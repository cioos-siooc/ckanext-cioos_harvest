# Helpers
# ---------------------------------------------------------------------------


def _json_default(obj):
    """Handle bytes returned by lxml when XPath hits element nodes."""
    if isinstance(obj, bytes):
        return obj.decode("utf-8", errors="replace")
    raise TypeError(f"Object of type {type(obj).__name__} is not JSON serializable")


def _normalise(value):
    """Round-trip through JSON to convert bytes → str."""
    return json.loads(json.dumps(value, default=_json_default))


def _normalise_extras(extras) -> dict:
    """Convert the extras field to a canonical sorted dict for comparison.

    Handles two forms:
    - ``list`` of ``{"key": k, "value": v}`` dicts — produced by the pipeline
    - ``dict`` — stored when a golden file was already normalised by this helper

    Production-only extras keys (harvest infrastructure, post-harvest scripts)
    are stripped via ``_EXTRAS_SKIP_KEYS``.  Python ``bool`` values are
    lowercased to match CKAN's DB round-trip (``True`` → ``"true"``).
    """
    if isinstance(extras, dict):
        items = extras.items()
    else:
        items = ((e["key"], e["value"]) for e in extras)

    result = {}
    for key, value in items:
        if key in _EXTRAS_SKIP_KEYS:
            continue
        if isinstance(value, bool):
            value = str(value).lower()
        result[key] = value
    return dict(sorted(result.items()))


def _filter_resource(resource: dict) -> dict:
    """Strip DB-generated and enrichment-service fields from a resource dict."""
    return {k: v for k, v in resource.items() if k not in _RESOURCE_SKIP_FIELDS}


def _filter(pkg: dict) -> dict:
    """Strip DB-generated and enrichment-service fields before comparison."""
    result = {k: v for k, v in pkg.items() if k not in _SKIP_FIELDS}
    if "extras" in result:
        result["extras"] = _normalise_extras(result["extras"])
    if "resources" in result:
        result["resources"] = [_filter_resource(r) for r in result["resources"]]
    return result


def _make_mock_harvest_object(guid: str) -> MagicMock:
    """Return a minimal mock HarvestObject that satisfies get_package_dict().

    Only the attributes actually read by SpatialHarvester / WAFHarvesterISO19115_3
    need to be set; everything else is covered by MagicMock auto-creation.
    """
    ho = MagicMock()
    ho.guid = guid
    ho.package = None
    ho.source.id = "00000000-0000-0000-0000-000000000001"
    ho.source.config = "{}"
    ho.source.title = "Test Harvest Source"
    ho.source.url = "http://test.example.com"
    ho.job.source.id = "00000000-0000-0000-0000-000000000001"
    ho.job.source.url = "http://test.example.com"
    ho.job.source.title = "Test Harvest Source"
    ho.job.id = "00000000-0000-0000-0000-000000000002"
    ho.id = "00000000-0000-0000-0000-000000000003"
    return ho


def _fixture_names():
    if not _XML_DIR.exists():
        return []
    return sorted(p.stem for p in _XML_DIR.glob("*.xml"))


